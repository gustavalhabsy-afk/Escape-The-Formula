async function finishBusinessChallenge() {
  if (businessSubmitting) {
    return;
  }

  businessSubmitting = true;

  const result = document.getElementById("businessResult");

  if (!result) {
    console.error("Elemen businessResult tidak ditemukan!");
    return;
  }

  // Tampilkan proses penyimpanan
  result.innerHTML = `
    <div class="business-mission">
      <h2>⏳ Menyimpan Nilai...</h2>
      <p>Mohon tunggu, nilai Business Challenge sedang disimpan.</p>
    </div>
  `;

  // Kirim nilai ke MongoDB
  const saveResult = await submitBusinessResult();

  if (saveResult.alreadyCompleted) {
    result.innerHTML = `
      <div class="business-mission">
        <h2>⚠️ Tantangan Sudah Pernah Diselesaikan</h2>
        <p>NIS ini sudah memiliki nilai sebelumnya.</p>
        <p>Nilai baru tidak disimpan.</p>
        <button onclick="closeBusinessChallenge()">
          Kembali ke Permainan
        </button>
      </div>
    `;
    return;
  }

  if (!saveResult.ok) {
    businessSubmitting = false;

    result.innerHTML = `
      <div class="business-mission">
        <h2>⚠️ Gagal Menyimpan Nilai</h2>
        <p>Periksa koneksi internet dan coba lagi.</p>
        <button onclick="finishBusinessChallenge()">
          Coba Simpan Lagi
        </button>
      </div>
    `;
    return;
  }

  // Tampilkan hasil setelah berhasil disimpan
  result.innerHTML = `
    <div class="business-mission">

      <h2 style="color: #fbbf24;">
        🏆 BUSINESS CHALLENGE SELESAI!
      </h2>

      <p>
        Selamat! Kamu berhasil menyelesaikan
        seluruh tantangan pengelolaan usaha UMKM.
      </p>

      <h3>📊 Rekap Pembelajaran</h3>

      <p>✓ Misi 1: Mengoptimalkan keuntungan (+25)</p>
      <p>✓ Misi 2: Menentukan jumlah permintaan (+25)</p>
      <p>✓ Misi 3: Menganalisis hubungan harga dan penjualan (+25)</p>
      <p>✓ Misi 4: Menghitung Break Even Point (+25)</p>

      <h3 style="color: #65df91;">
        Total Skor Business Challenge
      </h3>

      <h2 style="color: #fbbf24;">
        ${businessScore} / 100
      </h2>

      <p>✅ Nilai berhasil disimpan!</p>
      <p>Kamu berhasil menjadi pengusaha hebat!</p>

      <button onclick="closeBusinessChallenge()">
        Kembali ke Permainan
      </button>

    </div>
  `;
}


