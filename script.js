const PLAYER_SPEED = 4.2;           // kecepatan gerak, dalam satuan sel/detik
// Hitbox player = area kecil di KAKI (bagian bawah sprite), bukan seluruh kotak sel.
// Nilai 0..1 relatif terhadap sel. Cocok dengan sudut pandang top-down: kepala boleh
// "menutupi" dinding, tapi kaki tidak boleh masuk.
const PLAYER_FOOT = { l: 0.30, r: 0.70, t: 0.75, b: 0.96 };

