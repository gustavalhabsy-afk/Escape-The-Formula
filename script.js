(function setupTouchControls() {
  const box = document.getElementById("touch-controls");
  const joy = document.getElementById("joystick");
  const stick = document.getElementById("stick");
  if (!box || !joy || !stick) return;
  const force = new URLSearchParams(location.search).has("touch");
  const isTouch = force
    || window.matchMedia("(pointer: coarse)").matches
    || "ontouchstart" in window
    || navigator.maxTouchPoints > 0;
  if (!isTouch) return;
  box.classList.remove("hidden");

  const fire = (type, key, repeat = false) =>
    document.dispatchEvent(new KeyboardEvent(type, {
      key, code: key === " " ? "Space" : key, repeat, bubbles: true, cancelable: true
    }));

  // ---------- Joystick ----------
  const THRESH = 0.35;   // semakin besar, semakin harus digeser jauh
  const held = new Set();
  let activeId = null, timer = null;

  function setDirs(next) {
    for (const k of [...held]) if (!next.has(k)) { held.delete(k); fire("keyup", k); }
    for (const k of next) if (!held.has(k)) { held.add(k); fire("keydown", k); }
  }

  function update(e) {
    const r = joy.getBoundingClientRect();
    const R = r.width / 2;
    let dx = e.clientX - (r.left + R);
    let dy = e.clientY - (r.top + R);
    const dist = Math.hypot(dx, dy);
    if (dist > R) { dx = dx / dist * R; dy = dy / dist * R; }
    stick.style.transform = `translate(${dx}px, ${dy}px)`;

    const nx = dx / R, ny = dy / R;
    const next = new Set();
    if (nx > THRESH) next.add("ArrowRight");
    if (nx < -THRESH) next.add("ArrowLeft");
    if (ny > THRESH) next.add("ArrowDown");
    if (ny < -THRESH) next.add("ArrowUp");
    setDirs(next);
  }

  function release() {
    activeId = null;
    clearInterval(timer); timer = null;
    stick.classList.remove("active");
    stick.style.transform = "";
    setDirs(new Set());
  }

  joy.addEventListener("pointerdown", (e) => {
    if (activeId !== null) return;
    e.preventDefault();
    activeId = e.pointerId;
    joy.setPointerCapture(e.pointerId);
    stick.classList.add("active");
    update(e);
    // meniru auto-repeat keyboard saat joystick ditahan
    timer = setInterval(() => held.forEach((k) => fire("keydown", k, true)), 100);
  });
  joy.addEventListener("pointermove", (e) => { if (e.pointerId === activeId) update(e); });
  ["pointerup", "pointercancel", "lostpointercapture"].forEach((ev) =>
    joy.addEventListener(ev, (e) => { if (e.pointerId === activeId) release(); }));
  joy.addEventListener("contextmenu", (e) => e.preventDefault());

  // ---------- Tombol aksi ----------
  box.querySelectorAll(".actions button").forEach((btn) => {
    const key = btn.dataset.key;
    btn.addEventListener("pointerdown", (e) => { e.preventDefault(); fire("keydown", key); });
    ["pointerup", "pointercancel", "pointerleave"].forEach((ev) =>
      btn.addEventListener(ev, (e) => { e.preventDefault(); fire("keyup", key); }));
    btn.addEventListener("contextmenu", (e) => e.preventDefault());
  });
})();


