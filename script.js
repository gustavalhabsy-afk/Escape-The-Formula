function clamp(v, min, max) {
  return Math.max(min, Math.min(max, v));
}

/** Apakah hitbox kaki player (di posisi x,y satuan sel) menabrak dinding/rintangan? */
function collidesWithWalls(x, y) {
  const l = x + PLAYER_FOOT.l;
  const t = y + PLAYER_FOOT.t;
  const r = x + PLAYER_FOOT.r;
  const b = y + PLAYER_FOOT.b;
  for (const w of currentWalls) {
    if (r > w.l && l < w.r && b > w.t && t < w.b) return true;
  }
  return false;
}

/** Apakah hitbox kaki player (di x,y) menyentuh area sentuh NPC/boss di sel (cellX,cellY)? */
function boxOverlapsCell(x, y, cellX, cellY) {
  const l = x + PLAYER_FOOT.l;
  const t = y + PLAYER_FOOT.t;
  const r = x + PLAYER_FOOT.r;
  const b = y + PLAYER_FOOT.b;
  // area sentuh NPC: hampir seluruh sel, sedikit lebih kecil di sisi atas/kiri/kanan
  return r > cellX + 0.1 && l < cellX + 0.9 && b > cellY + 0.2 && t < cellY + 1.0;
}

/** Cari NPC/boss hidup yang bertabrakan dengan kotak player di posisi x,y. */
function findBlockingEntity(x, y) {
  for (const npc of state.npcs) {
    if (!npc.defeated && boxOverlapsCell(x, y, npc.x, npc.y)) {
      return { type: "npc", entity: npc };
    }
  }
  if (state.boss && !state.boss.defeated && boxOverlapsCell(x, y, state.boss.x, state.boss.y)) {
    return { type: "boss", entity: state.boss };
  }
  return null;
}

